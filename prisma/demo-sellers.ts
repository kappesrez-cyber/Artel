/** Репутация, документы и внешние проверки продавца по его уровню. Детерминированно по `i`. */
export function sellerProfile(seller: DemoSeller, i: number) {
  const n = (mod: number) => (i * 7 + 3) % mod;
  const base = {
    reliable: { completed: 24 + n(18), cancelled: n(2), ratings: [5, 5, 5, 4, 5, 5] },
    solid: { completed: 10 + n(10), cancelled: 1, ratings: [5, 4, 4, 5, 4] },
    young: { completed: 2 + n(5), cancelled: 0, ratings: [5, 5, 4] },
    late: { completed: 12 + n(8), cancelled: 3 + n(2), ratings: [4, 3, 3, 4, 2, 4] },
    reseller: { completed: 1, cancelled: 2 + n(2), ratings: [2, 3] },
  }[seller.tier];
  const reputation = { ...base, reviews: reviewTexts[seller.tier] };

  const certificate = {
    kind: "CERTIFICATE" as const,
    title: "Декларация соответствия ЕАЭС",
    number: `ЕАЭС N RU Д-RU.${String(10_100 + i).padStart(5, "0")}`,
    issuedAt: `${Math.min(2025, Math.max(seller.foundedYear, 2021))}-0${1 + (i % 9)}-15`,
  };
  const documents =
    seller.tier === "reseller"
      ? []
      : [
          ...financials(seller.tier === "young" ? seller.foundedYear : seller.foundedYear + 1),
          certificate,
          ...(seller.tier === "reliable"
            ? [
                {
                  kind: "QUALITY" as const,
                  title: "Система менеджмента качества ISO 9001:2015",
                  number: `ISO-9001-${1000 + i}`,
                  issuedAt: "2024-06-01",
                },
              ]
            : []),
        ];

  const external: ExternalChecks = {
    reliable: {
      facts: [
        { kind: "ok" as const, text: "Производственная площадка подтверждена видеоаудитом" },
        { kind: "ok" as const, text: "Арбитражных дел в роли ответчика нет" },
        { kind: "ok" as const, text: "Выручка стабильно растёт последние три года" },
      ],
    },
    solid: {
      facts: [
        { kind: "ok" as const, text: "Цех и оборудование подтверждены фотоаудитом" },
        { kind: "ok" as const, text: "Налоговая история без нарушений" },
      ],
    },
    young: {
      facts: [
        { kind: "ok" as const, text: "Площадка и станки подтверждены видеоаудитом" },
        { kind: "warn" as const, text: "Компания молодая: истории поставок пока мало", weight: -1 },
      ],
    },
    late: {
      facts: [
        { kind: "ok" as const, text: "Производство подтверждено выездом" },
        { kind: "warn" as const, text: "Отгрузки задерживаются в среднем на 9–14 дней" },
        { kind: "bad" as const, text: "Иски о просрочке поставки в картотеке арбитражных дел" },
      ],
      flags: ["late" as const],
    },
    reseller: {
      facts: [
        { kind: "bad" as const, text: "Производства нет: по адресу офис в бизнес-центре" },
        { kind: "warn" as const, text: "Цены выше, чем у производителей тех же позиций" },
      ],
      flags: ["reseller" as const],
    },
  }[seller.tier];

  const products: DemoProduct[] = seller.products.map(
    ([name, article, analogs, description, price, leadTimeDays]) => ({
      name,
      article,
      analogs,
      description,
      price: String(price),
      leadTimeDays,
      city: seller.city,
      status: "PUBLISHED",
    }),
  );

  return {
    organization: {
      name: seller.name,
      inn: String(5_000_000_100 + i * 13),
      ogrn: String(1_150_000_000_100 + i * 17),
      city: seller.city,
      description: seller.description,
      phone: `+7 900 ${String(100 + i).padStart(3, "0")}-${String(10 + (i % 90)).padStart(2, "0")}-${String(20 + (i % 70)).padStart(2, "0")}`,
      foundedYear: seller.foundedYear,
      isSeller: true,
      isBuyer: true,
    },
    verified: seller.tier !== "reseller",
    documents,
    products,
    reputation,
    external,
  };
}
