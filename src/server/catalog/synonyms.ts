// Частые окончания русских слов. Сам поиск склоняет слова средствами PostgreSQL (`russian`),
// а эта грубая основа нужна, чтобы сопоставить слово запроса со словарём без базы.
const ENDINGS =
  /(иями|ями|ами|ией|ого|его|ому|ему|ыми|ими|ов|ев|ей|ой|ий|ый|ая|яя|ое|ее|ые|ие|ам|ям|ах|ях|ом|ем|ию|ия|а|я|о|е|ы|и|ь|у|ю|й)$/;

/** Грубая основа слова: отбрасываем окончание, если остаётся хотя бы 3 буквы. */
export function stem(word: string): string {
  const cut = word.replace(ENDINGS, "");
  return cut.length >= 3 ? cut : word;
}

const key = (word: string) => stem(word.toLowerCase().replaceAll("ё", "е"));

// Беглая гласная: «ремень» — «ремня», «уголок» — «уголка». Слово из словаря находим по обеим основам.
const withoutFleetingVowel = (base: string) => base.replace(/[ео]([^аеиоуыэюя])$/, "$1");

const index = new Map<string, Set<string>>();
for (const group of SYNONYM_GROUPS) {
  for (const entry of group) {
    // Многословные синонимы ищутся только целиком, поэтому ключ — вся фраза.
    const keys = entry.includes(" ") ? [entry] : [key(entry), withoutFleetingVowel(key(entry))];
    for (const k of new Set(keys)) {
      const set = index.get(k) ?? new Set<string>();
      for (const other of group) set.add(other);
      index.set(k, set);
    }
  }
}

/** Синонимы одного слова запроса (без самого слова). */
export function synonymsFor(word: string): string[] {
  const w = word.toLowerCase().replaceAll("ё", "е");
  return [...(index.get(key(w)) ?? [])].filter((s) => s !== w);
}
